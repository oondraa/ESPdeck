export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6;

/** Vrátí souřadnice rozsvícených bodů pro text; baseline = y posledního řádku + 1. */
export function textPixels(text: string, x0: number, baseline: number): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  const top = baseline - GLYPH_H;
  let x = x0;
  for (const ch of text) {
    const rows = RAW[ch] ?? RAW[' '];
    if (rows) {
      for (let r = 0; r < GLYPH_H; r++) {
        const row = rows[r] ?? '';
        for (let c = 0; c < GLYPH_W; c++) {
          if (row.charCodeAt(c) === 49) out.push([x + c, top + r]);
        }
      }
    }
    x += ADVANCE;
  }
  return out;
}
